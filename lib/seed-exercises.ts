function slug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

export const SEED_EXERCISES: Exercise[] = rows.map(([name, muscle, equipment]) => ({
  id: `builtin-${slug(name)}`,
  name,
  muscle,
  equipment,
  custom: false,
}));
